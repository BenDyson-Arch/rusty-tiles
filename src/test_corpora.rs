//! Generated validator test corpora. The fixtures under `bench/architecture_audit` that
//! the oracle-parity tests read are not committed: `scripts/test_corpora.py` writes them
//! from their tracked generators and checks every file against the tracked SHA-256
//! manifest (`bench/architecture_audit/generated-corpora.sha256`). Call [`ensure`] before
//! reading one. Library tests include this file as `crate::test_corpora`; integration
//! tests include it with `#[path]`.

use std::path::Path;
use std::process::Command;
use std::sync::OnceLock;

/// Runs `python3 scripts/test_corpora.py generate` once per test process. It rewrites any
/// missing or different generated file, then verifies them all. Panics, failing the
/// calling test, when no Python 3.12+ interpreter runs or any file still differs.
/// `RUSTY_TILES_PYTHON` names the interpreter; otherwise `python3`, then `python`.
pub fn ensure() {
    static GENERATED: OnceLock<Result<(), String>> = OnceLock::new();
    if let Err(message) = GENERATED.get_or_init(generate) {
        panic!("{message}");
    }
}

fn generate() -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let candidates = match std::env::var_os("RUSTY_TILES_PYTHON") {
        Some(python) => vec![python],
        None => vec!["python3".into(), "python".into()],
    };
    // A candidate counts only if it is Python 3.12 or later (the generated bytes depend on
    // 3.12's float sum()); on Windows `python3` can also be a store stub that exits with an error.
    let python = candidates
        .into_iter()
        .find(|python| {
            Command::new(python)
                .args(["-c", "import sys; sys.exit(sys.version_info < (3, 12))"])
                .output()
                .is_ok_and(|probe| probe.status.success())
        })
        .ok_or_else(|| {
            "generated test corpora: no Python 3.12+ interpreter (python3 or python) runs; \
             install one or set RUSTY_TILES_PYTHON"
                .to_owned()
        })?;
    let run = Command::new(&python)
        .arg(root.join("scripts/test_corpora.py"))
        .arg("generate")
        .current_dir(root)
        .output()
        .map_err(|error| format!("generated test corpora: {python:?}: {error}"))?;
    if run.status.success() {
        return Ok(());
    }
    Err(format!(
        "generated test corpora: `{} scripts/test_corpora.py generate` failed ({}):\n{}{}",
        python.to_string_lossy(),
        run.status,
        String::from_utf8_lossy(&run.stdout),
        String::from_utf8_lossy(&run.stderr)
    ))
}
