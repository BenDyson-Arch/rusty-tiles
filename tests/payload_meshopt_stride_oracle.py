"""Retain exact executions of the independently authored meshopt stride lane."""
import argparse
import base64
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess


def sha(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', type=Path, required=True)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    controls = root / 'bench/architecture_audit/c1_payload_integrity/production_controls'
    lanes = [
        # C2 amendment (2026-10-11): stride_controls/2026-10-10 with C2 report expectations,
        # then the validator-caps amendment (2026-10-11) with the raised limits defaults,
        # then the C2-WB cap amendment (2026-10-12): containmentWorkUnits 2^29,
        # then the VS-C limits amendment (2026-10-14): storedBytes, limitDerivation, null caps,
        # then the payload-element ratio amendment (2026-10-30): totalPayloadElements 25/byte.
        ('stride6', controls / 'payload_element_ratio_amendment/2026-10-30/stride_controls',
         '15ce7e3e98ce92d705ce08059e7a0200c4977af7968d569f721b176ffbe31ff2', 6),
        ('parent1', controls / 'stride_parent_control/2026-10-10',
         '9a049a589538aef1e0d5d566460b4200966063f6eda7b7007f08f3b0fdd063f0', 1),
        # Additive meshopt stream-header lane (2026-10-12, C1 rule H-1): one allowed header
        # per mode from the pinned EXT text, the other codec version and an unknown one.
        # VS-C limits amendment (2026-10-14): the same lane with the VS-C report expectations
        # (production_controls/vs_c_limits_amendment/2026-10-14/meshopt_header), then the ratio
        # amendment (payload_element_ratio_amendment/2026-10-30/meshopt_header).
        ('header9', controls / 'payload_element_ratio_amendment/2026-10-30/meshopt_header',
         'f8ef13dc13e9bb439862ff802c72166596d30a023b088d08ef57a8ba36222bb9', 9),
        # KHR_texture_basisu / KTX2 container lane (2026-10-13): archives are regenerated by
        # its runner from pinned references and checked against the frozen manifest.
        # VS-B budget amendment (2026-10-14): one admitted case over the budget crossovers
        # reports max(floor, kappa*S) (production_controls/vs_b_budget_amendment/2026-10-14).
        # VS-C limits amendment (2026-10-14): the runner applies the VS-C report rule to the
        # regenerated cases (production_controls/vs_c_limits_amendment/2026-10-14, --ktx2), then
        # the ratio rule (payload_element_ratio_amendment/2026-10-30, --ktx2).
        ('ktx2', controls / 'ktx2_basisu_amendment/2026-10-13', '1db021d2a5be07572f203272386b1687688382237519b6c7b377359ab7cf5d9f', 67),
    ]
    for _, lane, manifest_hash, _ in lanes:
        assert sha(lane / 'fixtures/manifest.json') == manifest_hash
        frozen = json.loads((lane / 'integrity.json').read_text())
        for name, record in frozen['files'].items():
            assert sha(lane / name) == record['sha256']
            assert (lane / name).stat().st_size == record['bytes']
    args.work.mkdir(parents=True, exist_ok=False)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    files = subprocess.check_output(['git', 'ls-files'], cwd=root, text=True).splitlines()
    selected = [name for name in files if name in ('Cargo.toml', 'Cargo.lock', 'build.rs', 'bindings/python/Cargo.toml')
                or name.startswith(('src/', 'bindings/python/src/')) and name.endswith('.rs')]
    pin = args.work / 'source-pin.json'
    pin.write_text(json.dumps({
        'source_commit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=root, text=True).strip(),
        'source_tree': subprocess.check_output(['git', 'rev-parse', 'HEAD^{tree}'], cwd=root, text=True).strip(),
        'production_sha256': {name: sha(root / name) for name in selected},
        'runner_sha256': sha(Path(__file__)),
        'scope': 'Actual selected checkout and supplied CLI; finite independent meshopt controls.',
    }, indent=2) + '\n')
    phases = {}
    for label, lane, _, count in lanes:
        spec = importlib.util.spec_from_file_location('independent_' + label, lane / 'runner.py')
        oracle = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(oracle)
        run_dir = args.work / label
        status = oracle.run(argparse.Namespace(binary=args.binary, binary_sha256=sha(args.binary),
                                              source_pin=pin, source_pin_sha256=sha(pin), run_dir=run_dir))
        receipt = json.loads((run_dir / 'receipt.json').read_text())
        for case in receipt['cases']:
            for stream in ('stdout', 'stderr'):
                raw = (run_dir / (case['name'] + '.' + stream)).read_bytes()
                assert hashlib.sha256(raw).hexdigest() == case[stream + 'Sha256']
                case[stream + 'Base64'] = base64.b64encode(raw).decode('ascii')
        receipt['runnerExitCode'] = status
        phases[label] = receipt
        evidence = {'coordinatorRunnerSha256': sha(Path(__file__)), 'phases': phases,
                    'scope': 'Actual independently authored six stride controls, separate parent-gate control, nine meshopt header controls and 67 KTX2 controls.'}
        args.output.write_text(json.dumps(evidence, indent=2) + '\n')
        assert status == 0 and receipt['passes'] == count and receipt['failures'] == 0, args.output



if __name__ == '__main__':
    main()
