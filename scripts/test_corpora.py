#!/usr/bin/env python3
"""Generate the validator test corpora and verify them against the tracked SHA-256 manifest.

The fixtures that the validator oracle tests read under bench/architecture_audit/ are not committed. Their
generators are, together with MANIFEST, which pins the SHA-256 of every generated file (`sha256sum` format,
paths relative to bench/architecture_audit/). The files are written in place, next to their generators, and are
gitignored.

    python3 scripts/test_corpora.py [generate]   write every missing or different file, then verify all of them
    python3 scripts/test_corpora.py check        verify only
    python3 scripts/test_corpora.py update       rerun every generator and rewrite MANIFEST from its output

`generate` reruns a generator only when one of its files is missing or differs, so a second run only hashes
(well under a second). Any file that still differs from MANIFEST afterwards is listed and the exit status is 1;
nothing is skipped. Library and integration tests that read these files call `generate` first
(src/test_corpora.rs), and CI runs it before the tests. `update` is for an intended generator change: review
the MANIFEST diff, and the generator's own records (manifest.json, report.json), in the same commit.

Each generator runs with `--fixtures-only` (or into a temporary directory, see JOBS): it writes fixtures and
leaves its committed records alone. Python 3.12 or later, standard library only; the bytes do not depend on
the platform or the Python version from 3.12 on (3.12 made the built-in sum() of floats compensated, and the C2
witness builder sums float products with it). A file that cannot be regenerated byte for byte stays committed and is not listed here
(bench/architecture_audit/README.md lists them).
"""
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIT = "bench/architecture_audit"
MANIFEST = AUDIT + "/generated-corpora.sha256"
LOCK = AUDIT + "/.generated-corpora.lock"
MINIMUM_PYTHON = (3, 12)
I1 = AUDIT + "/implicit_read"
C2 = AUDIT + "/c2_decoded_containment"
C1_CONTEXT = AUDIT + "/c1_payload_integrity/production_controls/context_controls/2026-10-10"

# Every generator runs under this shim. It pins the one platform-dependent field the standard library writes into
# a ZIP: ZipInfo sets create_system to 0 on Windows and 3 (Unix) elsewhere, and the committed fixtures say 3. The
# script then runs as `python3 -I script args` would (its directory first on sys.path). `-X utf8` makes text reads
# decode UTF-8 whatever the locale. Text files are written with `\n` line endings: on Windows a text-mode write
# would otherwise translate them to `\r\n` and the bytes would not match the manifest.
SHIM = """
import builtins, io, os, runpy, sys, zipfile
_init = zipfile.ZipInfo.__init__
def _unix(self, *args, **kwargs):
    _init(self, *args, **kwargs)
    self.create_system = 3
zipfile.ZipInfo.__init__ = _unix
_open = io.open
def _lf(file, mode="r", buffering=-1, encoding=None, errors=None, newline=None, *args, **kwargs):
    if newline is None and "b" not in mode and any(c in mode for c in "wax+"):
        newline = "\\n"
    return _open(file, mode, buffering, encoding, errors, newline, *args, **kwargs)
builtins.open = io.open = _lf
script = os.path.abspath(sys.argv[1])
sys.argv = sys.argv[1:]
sys.path.insert(0, os.path.dirname(script))
runpy.run_path(script, run_name="__main__")
"""


def python(cwd, script, *args):
    command = [sys.executable, "-I", "-X", "utf8", "-c", SHIM, script, *args]
    done = subprocess.run(command, cwd=os.path.join(ROOT, cwd), stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if done.returncode:
        sys.stdout.write(done.stdout.decode("utf-8", "replace"))
        raise SystemExit("`%s` (in %s) exited with %d" % (" ".join((script,) + args), cwd, done.returncode))


def i1_controls(tmp):
    python(I1, "witnesses/generate.py", "--fixtures-only")


def c2_witnesses(tmp):
    python(C2, "witnesses/generate.py", "--fixtures-only")


def c2_wb(tmp):
    python(C2, "wb/generate.py", "--fixtures-only")


def c2_h11(tmp):
    python(C2, "h11/generate.py", "--fixtures-only")


def c2_slice3(tmp):
    # S3-19 controls are I1 controls as generated before amendment 6, by the frozen generator in pre_amendment6/.
    pre = os.path.join(tmp, "pre-amendment-6")
    python(C2, "controls/slice3/pre_amendment6/run.py", pre)
    python(C2, "controls/slice3/generate.py", "--pre-amendment", os.path.join(pre, "controls"), "--fixtures-only")


def c1_context(tmp):
    # The generator writes into a new directory; fixtures/manifest.json stays committed (hand-amended labels,
    # compiled in with include_str!), so every other file is copied.
    out = os.path.join(tmp, "context")
    python(C1_CONTEXT, "generate.py", "--generate", out)
    target = os.path.join(ROOT, C1_CONTEXT, "fixtures")
    for directory, _, files in os.walk(out):
        for name in files:
            source = os.path.join(directory, name)
            relative = os.path.relpath(source, out)
            if relative != "manifest.json":
                os.makedirs(os.path.dirname(os.path.join(target, relative)), exist_ok=True)
                shutil.copyfile(source, os.path.join(target, relative))


# (name, directories whose generated files the job writes, function(temporary directory)).
JOBS = [
    ("I1 controls", [I1 + "/controls/fixtures/"], i1_controls),
    ("C2 witnesses and controls", [C2 + "/witnesses/fixtures/", C2 + "/controls/fixtures/"], c2_witnesses),
    ("C2-WB class fixtures", [C2 + "/wb/fixtures/"], c2_wb),
    ("C2 H11 fast-path controls", [C2 + "/h11/fixtures/"], c2_h11),
    ("C2 slice-3 controls", [C2 + "/controls/slice3/fixtures/"], c2_slice3),
    ("C1 context controls", [C1_CONTEXT + "/fixtures/"], c1_context),
]


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def read_manifest():
    entries = {}
    with open(os.path.join(ROOT, MANIFEST), encoding="utf-8") as fh:
        for number, line in enumerate(fh, 1):
            digest, sep, path = line.rstrip("\r\n").partition("  ")
            path = AUDIT + "/" + path
            if not sep or len(digest) != 64 or path in entries:
                raise SystemExit("%s:%d: expected one '<sha256>  <path>' line per file" % (MANIFEST, number))
            entries[path] = digest
    return entries


def owner(path):
    for index, (_, prefixes, _) in enumerate(JOBS):
        if any(path.startswith(prefix) for prefix in prefixes):
            return index
    raise SystemExit("%s: %s is not written by any job in scripts/test_corpora.py" % (MANIFEST, path))


def problems(entries):
    """{path: 'missing' | 'differs'} for every manifest file that does not match."""
    bad = {}
    for path, digest in entries.items():
        full = os.path.join(ROOT, path)
        if not os.path.isfile(full):
            bad[path] = "missing"
        elif sha256(full) != digest:
            bad[path] = "differs"
    return bad


def run_job(index):
    name, _, job = JOBS[index]
    started = time.monotonic()
    with tempfile.TemporaryDirectory(prefix="rusty-tiles-corpora-") as tmp:
        try:
            job(tmp)
        except SystemExit as failure:
            raise SystemExit("%s: %s" % (name, failure.code))
    print("generated %-28s %5.1f s" % (name, time.monotonic() - started))


class Lock:
    """One generator run at a time across processes (parallel test binaries share the output files)."""

    def __enter__(self):
        self.fh = open(os.path.join(ROOT, LOCK), "a+b")
        if os.name == "nt":
            import msvcrt
            while True:
                try:
                    self.fh.seek(0)
                    msvcrt.locking(self.fh.fileno(), msvcrt.LK_LOCK, 1)
                    break
                except OSError:  # LK_LOCK gives up after about ten seconds; keep waiting
                    pass
        else:
            import fcntl
            fcntl.flock(self.fh, fcntl.LOCK_EX)
        return self

    def __exit__(self, *exc):
        self.fh.close()  # releases the lock


def report(bad):
    for path, what in sorted(bad.items()):
        print("%s: %s" % (what, path))
    print("%d generated file(s) do not match %s; rerun `python3 scripts/test_corpora.py`, or after an "
          "intended generator change `python3 scripts/test_corpora.py update`" % (len(bad), MANIFEST))
    return 1


def generate(entries):
    with Lock():
        bad = problems(entries)
        for index in sorted({owner(path) for path in bad}):
            run_job(index)
        if bad:
            bad = problems(entries)
    if bad:
        return report(bad)
    print("%d generated files match %s" % (len(entries), MANIFEST))
    return 0


def update():
    with Lock():
        for index in range(len(JOBS)):
            run_job(index)
        prefixes = [prefix for _, dirs, _ in JOBS for prefix in dirs]
        tracked = set(subprocess.run(["git", "ls-files", "-z", "--", *prefixes], cwd=ROOT, check=True,
                                     stdout=subprocess.PIPE).stdout.decode("utf-8").split("\0"))
        entries = {}
        for prefix in prefixes:
            for directory, dirs, files in os.walk(os.path.join(ROOT, prefix)):
                dirs[:] = sorted(d for d in dirs if d != "__pycache__")
                for name in files:
                    path = os.path.relpath(os.path.join(directory, name), ROOT).replace(os.sep, "/")
                    if path not in tracked:
                        entries[path] = sha256(os.path.join(ROOT, path))
    with open(os.path.join(ROOT, MANIFEST), "w", encoding="utf-8", newline="\n") as fh:
        fh.writelines("%s  %s\n" % (entries[path], path[len(AUDIT) + 1:]) for path in sorted(entries))
    print("%s: %d files" % (MANIFEST, len(entries)))
    return 0


def main(argv):
    if sys.version_info < MINIMUM_PYTHON:
        raise SystemExit("scripts/test_corpora.py needs Python %d.%d or later (this is %s)"
                         % (MINIMUM_PYTHON + (sys.version.split()[0],)))
    command = argv[0] if argv else "generate"
    if len(argv) > 1 or command not in ("generate", "check", "update"):
        raise SystemExit(__doc__)
    if command == "update":
        return update()
    entries = read_manifest()
    for path in entries:
        owner(path)
    if command == "check":
        bad = problems(entries)
        if bad:
            return report(bad)
        print("%d generated files match %s" % (len(entries), MANIFEST))
        return 0
    return generate(entries)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
