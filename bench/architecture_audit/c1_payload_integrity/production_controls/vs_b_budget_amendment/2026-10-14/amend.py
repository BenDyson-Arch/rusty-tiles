#!/usr/bin/env python3
"""VS-B budget amendment of the frozen C1 payload-control expectations (2026-10-14).

    python3 -I amend.py ARCHIVE_ROOT          # amend the KTX2 lane manifest in place
    python3 -I amend.py ARCHIVE_ROOT --check  # recompute and compare, change nothing

Rule (docs/architecture/validator-traversal-scale-amendment.md, VS-B-2): default validation
reports each of the seven amplification budgets as max(old default, kappa * S), where S is the
sum of the archive's stored member sizes, kappa = 1/8 (hierarchyVisits, references), 4
(totalBytesRead, containmentBytesRead), 16 (totalPayloadElements, containmentDecodedBytes)
and 128 (containmentWorkUnits), with integer division. S is read here from the regenerated
archive's ZIP directory with Python's zipfile (stored entries: compressed size = size), never
from the validator. Only admitted cases whose S exceeds a crossover change, and only in
expectedReport.limits; the old value is asserted first (an already amended value is kept).
ARCHIVE_ROOT is a runner.py work directory holding `<case>/input.3tz` (archives are
regenerated byte for byte, not tracked). The lane's runner.py applies `amend_cases` to the
regenerated cases before comparing them with the frozen manifest, and this script records
the runner's new hash in the manifest.
"""
import hashlib
import json
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LANE = HERE.parents[1] / "ktx2_basisu_amendment/2026-10-13"
KAPPA = {"hierarchyVisits": (1, 8), "references": (1, 8), "totalBytesRead": (4, 1),
         "containmentBytesRead": (4, 1), "totalPayloadElements": (16, 1),
         "containmentDecodedBytes": (16, 1), "containmentWorkUnits": (128, 1)}
FLOOR = {"hierarchyVisits": 262144, "references": 1048576, "totalBytesRead": 2147483648,
         "containmentBytesRead": 2147483648, "totalPayloadElements": 16000000,
         "containmentDecodedBytes": 2147483648, "containmentWorkUnits": 536870912}


def stored_bytes(path):
    with zipfile.ZipFile(path) as archive:
        assert all(i.compress_type == zipfile.ZIP_STORED for i in archive.infolist())
        return sum(i.compress_size for i in archive.infolist())


def amend_cases(cases, root):
    """The VS-B-2 rule on every admitted case's expected limits; returns (cases, changes)."""
    changed = []
    for case in cases:
        if case["expectedCategory"] != "admitted":
            continue
        archive = Path(root) / case["path"]
        assert hashlib.sha256(archive.read_bytes()).hexdigest() == case["sha256"], case["name"]
        s = stored_bytes(archive)
        # The generator may share one limits object between cases: amend a copy.
        limits = case["expectedReport"]["limits"] = dict(case["expectedReport"]["limits"])
        for key, (num, den) in KAPPA.items():
            want = max(FLOOR[key], s * num // den)
            if limits[key] != want:
                assert limits[key] == FLOOR[key], (case["name"], key, limits[key])
                limits[key] = want
                changed.append((case["name"], key, want, s))
    return cases, changed


def main(argv):
    root, check = Path(argv[0]), "--check" in argv
    path = LANE / "fixtures/manifest.json"
    raw = path.read_bytes()
    manifest = json.loads(raw)
    manifest["cases"], changed = amend_cases(manifest["cases"], root)
    manifest["runnerSha256"] = hashlib.sha256((LANE / "runner.py").read_bytes()).hexdigest()
    out = (json.dumps(manifest, indent=2) + "\n").encode()
    print(json.dumps({"changed": changed}))
    if check:
        return 0 if out == raw else 1
    path.write_bytes(out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
