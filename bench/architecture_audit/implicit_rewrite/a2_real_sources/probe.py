def literal_las(path, points):
    """Author format-0 LAS1.2 with source positions exactly integer*0.001."""
    raw = [tuple(round(v*1000) for v in p) for p in points]
    h = bytearray(227); h[:4] = b'LASF'; h[24:26] = bytes([1, 2])
    struct.pack_into('<HII', h, 94, 227, 227, 0)
    struct.pack_into('<BHI', h, 104, 0, 20, len(raw))
    struct.pack_into('<I', h, 111, len(raw))
    struct.pack_into('<3d', h, 131, .001, .001, .001)
    for a in range(3):
        struct.pack_into('<2d', h, 179+16*a, max(p[a] for p in raw)*.001, min(p[a] for p in raw)*.001)
    records = b''.join(struct.pack('<iiiHBBbBH', *p, index*101, 9, index % 32, 0, 0, index)
                       for index, p in enumerate(raw))
    path.write_bytes(h+records)
    # Enumerate source bytes, separately from the floating authored input.
    data = path.read_bytes(); count = struct.unpack_from('<I', data, 107)[0]
    scale = struct.unpack_from('<3d', data, 131); offset = struct.unpack_from('<3d', data, 155)
    return [[v*scale[a]+offset[a] for a, v in enumerate(struct.unpack_from('<3i', data, 227+20*i))]
            for i in range(count)]


