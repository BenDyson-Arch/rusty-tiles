"""Shared pieces of the milestone-4 scale-gate harness: output roots, disk preflight,
a portable counter-based PRNG, streamed glTF/GLB writing and manifests.

Everything here streams: callers hand over one bounded chunk (one cell, one region)
at a time and the writer appends it to disk, keeping only accessor metadata in RAM.
Generated bytes use only IEEE-exact NumPy arithmetic (+, -, *, /, sqrt) and integer
hashing, never libm trigonometry, so a seed reproduces the same bytes on any
platform with the same writer version. PNGs use stored (uncompressed) deflate blocks
for the same reason.
"""
import hashlib, json, os, pathlib, platform, shutil, struct, sys, time

import numpy as np

SCALE_ROOT = pathlib.Path(os.environ.get('RUSTY_TILES_SCALE_ROOT', pathlib.Path.home() / '.cache/rusty-tiles-scale'))
WRITER_VERSION = 1
FORBIDDEN_ROOTS = ('/tmp', '/dev/shm', '/run', '/var/tmp')
MiB, GiB = 1 << 20, 1 << 30

# glTF component types
FLOAT, UINT, USHORT, UBYTE = 5126, 5125, 5123, 5121
ARRAY_BUFFER, ELEMENT_ARRAY_BUFFER = 34962, 34963
NP_COMPONENT = {np.dtype('<f4'): FLOAT, np.dtype('<u4'): UINT, np.dtype('<u2'): USHORT, np.dtype('u1'): UBYTE}
TYPE_WIDTH = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}


# ---------------------------------------------------------------- paths and disk

def git_root():
    here = pathlib.Path(__file__).resolve()
    for parent in here.parents:
        if (parent / '.git').exists():
            return parent
    return None


def resolve_output(path, allow_anywhere=False):
    """Generated data lives under SCALE_ROOT (or an explicit cache path), never in /tmp or git."""
    out = pathlib.Path(path).expanduser()
    if not out.is_absolute():
        out = SCALE_ROOT / out
    out = out.resolve()
    if not allow_anywhere:
        text = str(out)
        if any(text == root or text.startswith(root + '/') for root in FORBIDDEN_ROOTS):
            raise SystemExit(f'refusing to write generated data under {out}: use {SCALE_ROOT}')
        for parent in [out, *out.parents]:
            if (parent / '.git').exists():
                raise SystemExit(f'refusing to write generated data inside the git tree {parent}')
    return out


def prepare_output(path, force):
    """Resolve an output directory; replacing a non-empty one needs --force, must lie strictly inside
    SCALE_ROOT and must hold an earlier generator manifest, so --force cannot delete arbitrary trees."""
    out = resolve_output(path)
    if out.exists() and any(out.iterdir()):
        if not force:
            raise SystemExit(f'{out} is not empty (use --force to replace)')
        root = SCALE_ROOT.resolve()
        if root not in out.parents or not (out / 'manifest.json').is_file():
            raise SystemExit(f'--force replaces only earlier generator output (with manifest.json) inside {root}')
        shutil.rmtree(out)
    return out


def free_bytes(path):
    probe = pathlib.Path(path)
    while not probe.exists():
        probe = probe.parent
    return shutil.disk_usage(probe).free


def disk_preflight(path, need_bytes, reserve_bytes=20 * GiB, what='output'):
    """Refuse before writing anything when need + reserve exceeds free space."""
    free = free_bytes(path)
    record = dict(path=str(path), need_bytes=int(need_bytes), reserve_bytes=int(reserve_bytes), free_bytes=free)
    if need_bytes + reserve_bytes > free:
        raise SystemExit(f'disk preflight refused {what}: need {need_bytes / GiB:.2f} GiB + reserve '
                         f'{reserve_bytes / GiB:.2f} GiB > free {free / GiB:.2f} GiB at {path}')
    return record


def sha256_file(path, block=8 * MiB):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        while chunk := f.read(block):
            h.update(chunk)
    return h.hexdigest()


def environment():
    return dict(python=sys.version.split()[0], numpy=np.__version__, platform=platform.platform(),
                machine=platform.machine(), writer_version=WRITER_VERSION)


def write_manifest(directory, kind, parameters, files, truth=None, extra=None):
    """manifest.json: parameters, environment, sha256 + size of every generated file and the truth record."""
    directory = pathlib.Path(directory)
    entries = {}
    for path in sorted(files):
        p = directory / path
        entries[str(path)] = dict(bytes=p.stat().st_size, sha256=sha256_file(p))
    script = pathlib.Path(sys.argv[0]).resolve()
    manifest = dict(schema=1, kind=kind, generator=script.name,
                    generator_sha256=sha256_file(script) if script.is_file() else None,
                    common_sha256=sha256_file(__file__), parameters=parameters, environment=environment(),
                    created_unix=int(time.time()), files=entries, total_bytes=sum(e['bytes'] for e in entries.values()),
                    truth=truth or {})
    if extra:
        manifest.update(extra)
    (directory / 'manifest.json').write_text(json.dumps(manifest, indent=2, sort_keys=False) + '\n')
    return manifest


# ---------------------------------------------------------------- deterministic randomness

M64 = np.uint64(0xFFFFFFFFFFFFFFFF)


def mix64(x):
    """splitmix64 finaliser on uint64 arrays (wrapping integer arithmetic, platform independent)."""
    x = np.asarray(x, dtype=np.uint64)
    with np.errstate(over='ignore'):
        x = x + np.uint64(0x9E3779B97F4A7C15)
        x = (x ^ (x >> np.uint64(30))) * np.uint64(0xBF58476D1CE4E5B9)
        x = (x ^ (x >> np.uint64(27))) * np.uint64(0x94D049BB133111EB)
        x = x ^ (x >> np.uint64(31))
    return x


def key(*parts):
    """Combine integer parts into one uint64 stream key."""
    acc = np.uint64(0x243F6A8885A308D3)
    with np.errstate(over='ignore'):
        for part in parts:
            acc = mix64(acc ^ np.uint64(int(part) & 0xFFFFFFFFFFFFFFFF))
    return acc


class Stream:
    """Counter-based uniform stream: value i of stream k is mix64(k + i). Same bytes everywhere."""

    def __init__(self, *parts):
        self.key = key(*parts)
        self.counter = 0

    def raw(self, n):
        with np.errstate(over='ignore'):
            out = mix64(self.key + np.arange(self.counter, self.counter + n, dtype=np.uint64))
        self.counter += n
        return out

    def uniform(self, n, low=0.0, high=1.0):
        u = (self.raw(n) >> np.uint64(11)).astype(np.float64) * (1.0 / (1 << 53))
        return low + (high - low) * u

    def integers(self, n, low, high):
        return (low + (self.raw(n) % np.uint64(high - low))).astype(np.int64)

    def normalish(self, n):
        """Irwin-Hall(4) rescaled to unit variance: bell-shaped without libm."""
        u = self.uniform(4 * n).reshape(n, 4).sum(axis=1)
        return (u - 2.0) * np.sqrt(3.0)


# ---------------------------------------------------------------- smooth value noise (no libm)

def _lattice(seed, ix, iz):
    with np.errstate(over='ignore'):
        h = mix64(np.uint64(int(seed) & 0xFFFFFFFFFFFFFFFF) ^ (ix.astype(np.int64).astype(np.uint64) * np.uint64(0x9E3779B97F4A7C15))
                  ^ (iz.astype(np.int64).astype(np.uint64) * np.uint64(0xC2B2AE3D27D4EB4F)))
    return (h >> np.uint64(11)).astype(np.float64) * (2.0 / (1 << 53)) - 1.0


def value_noise(seed, x, z, period=None):
    """Quintic-interpolated value noise in [-1, 1] and its analytic gradient; with a lattice
    period the noise tiles seamlessly (textures sampled with REPEAT)."""
    fx, fz = np.floor(x), np.floor(z)
    ix, iz = fx.astype(np.int64), fz.astype(np.int64)
    wrap = (lambda i: i % period) if period else (lambda i: i)
    tx, tz = x - fx, z - fz
    sx = tx * tx * tx * (tx * (tx * 6.0 - 15.0) + 10.0)
    sz = tz * tz * tz * (tz * (tz * 6.0 - 15.0) + 10.0)
    dsx = 30.0 * tx * tx * (tx * (tx - 2.0) + 1.0)
    dsz = 30.0 * tz * tz * (tz * (tz - 2.0) + 1.0)
    a, b = _lattice(seed, wrap(ix), wrap(iz)), _lattice(seed, wrap(ix + 1), wrap(iz))
    c, d = _lattice(seed, wrap(ix), wrap(iz + 1)), _lattice(seed, wrap(ix + 1), wrap(iz + 1))
    k1, k2, k3 = b - a, c - a, a - b - c + d
    value = a + k1 * sx + k2 * sz + k3 * sx * sz
    return value, (k1 + k3 * sz) * dsx, (k2 + k3 * sx) * dsz


def fbm(seed, x, z, frequency, amplitude, octaves, period=None):
    """Height and gradient (dh/dx, dh/dz) of fractal value noise. With period (lattice cells
    of the first octave over a unit domain) every octave tiles over [0, 1)."""
    h = np.zeros_like(x); gx = np.zeros_like(x); gz = np.zeros_like(x)
    f, a = frequency, amplitude
    for octave in range(octaves):
        p = period * (1 << octave) if period else None
        v, dx, dz = value_noise(seed + 7919 * octave, x * f, z * f, p)
        h += a * v; gx += a * f * dx; gz += a * f * dz
        f *= 2.0; a *= 0.5
    return h, gx, gz


def normalize(v):
    return v / np.sqrt((v * v).sum(axis=-1, keepdims=True))


# ---------------------------------------------------------------- streamed glTF writer

def _pad4(n):
    return (4 - n % 4) % 4


class GltfStream:
    """Append-only glTF writer. Binary data streams to .bin files (or one GLB BIN part file);
    JSON holds only the accessor/bufferView metadata of what was written.

    Buffers roll over at max_buffer_bytes so no single external file exceeds it; a view never
    spans buffers. For GLB output everything goes to one buffer and finish() assembles the GLB
    by streaming the part file after the JSON chunk."""

    def __init__(self, directory, stem, glb=False, max_buffer_bytes=1 * GiB):
        self.directory = pathlib.Path(directory)
        self.stem, self.glb = stem, glb
        self.max_buffer = (4 * GiB - 64 * MiB) if glb else max_buffer_bytes
        self.json = dict(asset=dict(version='2.0', generator=f'rusty-tiles scale_gates writer {WRITER_VERSION}'),
                         buffers=[], bufferViews=[], accessors=[], meshes=[], nodes=[], materials=[],
                         scenes=[dict(nodes=[])], scene=0)
        self.files = []
        self._file = None
        self._size = 0
        self._open_buffer()

    def _buffer_name(self, index):
        return f'{self.stem}.bin.part' if self.glb else f'{self.stem}-{index:04d}.bin'

    def _open_buffer(self):
        if self._file:
            self._close_buffer()
        index = len(self.json['buffers'])
        name = self._buffer_name(index)
        self._file = open(self.directory / name, 'wb')
        self._size = 0
        self.json['buffers'].append({} if self.glb else dict(uri=name))
        if not self.glb:
            self.files.append(name)

    def _close_buffer(self):
        pad = _pad4(self._size)
        if pad:
            self._file.write(b'\0' * pad); self._size += pad
        self._file.close()
        self.json['buffers'][-1]['byteLength'] = self._size
        self._file = None

    def view(self, arrays, target=None, stride=None):
        """Write arrays contiguously as one bufferView; returns (view index, [byte offsets])."""
        blobs = [np.ascontiguousarray(a) for a in arrays]
        total = sum(b.nbytes + _pad4(b.nbytes) for b in blobs)
        if total > self.max_buffer:
            raise ValueError(f'one bufferView of {total} bytes exceeds the buffer limit {self.max_buffer}')
        if self._size + total > self.max_buffer:
            if self.glb:
                raise ValueError('GLB output exceeds the 4 GiB container; use --format gltf')
            self._open_buffer()
        start, offsets, at = self._size, [], 0
        for b in blobs:
            offsets.append(at)
            self._file.write(b.tobytes(order='C'))
            pad = _pad4(b.nbytes)
            if pad:
                self._file.write(b'\0' * pad)
            at += b.nbytes + pad
        self._size += at
        # The view ends at the last array's data; its 4-byte alignment pad lies outside the view,
        # so an image view's bytes are exactly the image.
        record = dict(buffer=len(self.json['buffers']) - 1, byteOffset=start, byteLength=at - _pad4(blobs[-1].nbytes))
        if target:
            record['target'] = target
        if stride:
            record['byteStride'] = stride
        self.json['bufferViews'].append(record)
        return len(self.json['bufferViews']) - 1, offsets

    def accessor(self, view, offset, array, type_, minmax=False, normalized=False):
        array = np.asarray(array)
        record = dict(bufferView=view, componentType=NP_COMPONENT[array.dtype], count=int(array.shape[0]), type=type_)
        if offset:
            record['byteOffset'] = offset
        if normalized:
            record['normalized'] = True
        if minmax:
            flat = array.reshape(array.shape[0], -1)
            cast = float if array.dtype.kind == 'f' else int
            record['min'] = [cast(v) for v in flat.min(axis=0)]
            record['max'] = [cast(v) for v in flat.max(axis=0)]
        self.json['accessors'].append(record)
        return len(self.json['accessors']) - 1

    def primitive(self, attributes, indices, material):
        """Write one primitive as its own views (positions/normals/... tightly packed)."""
        names, arrays = zip(*attributes.items())
        out = {}
        for name, array in zip(names, arrays):
            view, _ = self.view([array], ARRAY_BUFFER)
            out[name] = self.accessor(view, 0, array, 'VEC%d' % array.shape[1] if array.ndim > 1 else 'SCALAR',
                                      minmax=(name == 'POSITION'))
        view, _ = self.view([indices], ELEMENT_ARRAY_BUFFER)
        prim = dict(attributes=out, indices=self.accessor(view, 0, indices, 'SCALAR'), mode=4)
        if material is not None:
            prim['material'] = material
        return prim

    def packed_primitives(self, prims):
        """Write many small primitives sharing one strided view per attribute (and one index view).
        prims: list of (attributes dict, indices, material). Attribute sets must match."""
        names = list(prims[0][0].keys())
        out = [dict(attributes={}, mode=4) for _ in prims]
        for name in names:
            arrays = [p[0][name] for p in prims]
            stride = arrays[0].dtype.itemsize * (arrays[0].shape[1] if arrays[0].ndim > 1 else 1)
            view, offsets = self.view(arrays, ARRAY_BUFFER, stride=stride if stride % 4 == 0 else None)
            for o, a, off in zip(out, arrays, offsets):
                o['attributes'][name] = self.accessor(view, off, a, 'VEC%d' % a.shape[1], minmax=(name == 'POSITION'))
        view, offsets = self.view([p[1] for p in prims], ELEMENT_ARRAY_BUFFER)
        for o, p, off in zip(out, prims, offsets):
            o['indices'] = self.accessor(view, off, p[1], 'SCALAR')
            if p[2] is not None:
                o['material'] = p[2]
        return out

    def add_mesh_node(self, primitives, name=None, translation=None):
        mesh = dict(primitives=primitives)
        if name:
            mesh['name'] = name
        self.json['meshes'].append(mesh)
        node = dict(mesh=len(self.json['meshes']) - 1)
        if name:
            node['name'] = name
        if translation is not None:
            node['translation'] = [float(v) for v in translation]
        self.json['nodes'].append(node)
        self.json['scenes'][0]['nodes'].append(len(self.json['nodes']) - 1)

    def image_bytes(self, data, mime='image/png'):
        """GLB: embed in the BIN buffer. glTF callers write external files instead."""
        view, _ = self.view([np.frombuffer(data, dtype=np.uint8)])
        self.json.setdefault('images', []).append(dict(bufferView=view, mimeType=mime))
        return len(self.json['images']) - 1

    def finish(self):
        """Close buffers and write the .gltf (or assemble the .glb). Returns the generated file names."""
        self._close_buffer()
        for k in ('materials', 'meshes', 'nodes'):
            if not self.json[k]:
                del self.json[k]
        text = json.dumps(self.json, separators=(',', ':'), sort_keys=False).encode()
        if not self.glb:
            name = f'{self.stem}.gltf'
            (self.directory / name).write_bytes(text)
            return [name] + self.files
        text += b' ' * _pad4(len(text))
        part = self.directory / self._buffer_name(0)
        bin_len = part.stat().st_size
        total = 12 + 8 + len(text) + 8 + bin_len
        if total >= 4 * GiB:
            raise ValueError('GLB output exceeds the 4 GiB container; use --format gltf')
        name = f'{self.stem}.glb'
        with open(self.directory / name, 'wb') as out, open(part, 'rb') as src:
            out.write(struct.pack('<4sII', b'glTF', 2, total))
            out.write(struct.pack('<I4s', len(text), b'JSON')); out.write(text)
            out.write(struct.pack('<I4s', bin_len, b'BIN\0'))
            shutil.copyfileobj(src, out, 16 * MiB)
        part.unlink()
        return [name]


# ---------------------------------------------------------------- PNG without zlib compression

def _crc_chunk(tag, data):
    import zlib
    return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xFFFFFFFF)


def png_bytes(pixels, compress=False):
    """RGB/RGBA uint8 HxWxC -> PNG. Default stores deflate blocks (deterministic everywhere);
    compress=True uses zlib level 9 (smaller, zlib-build dependent bytes)."""
    import zlib
    h, w, c = pixels.shape
    raw = np.zeros((h, 1 + w * c), dtype=np.uint8)
    raw[:, 1:] = pixels.reshape(h, w * c)
    data = raw.tobytes()
    if compress:
        payload = zlib.compress(data, 9)
    else:
        blocks, pos = [b'\x78\x01'], 0
        while True:
            chunk = data[pos:pos + 65535]
            pos += len(chunk)
            final = pos >= len(data)
            blocks.append(struct.pack('<BHH', 1 if final else 0, len(chunk), len(chunk) ^ 0xFFFF) + chunk)
            if final:
                break
        blocks.append(struct.pack('>I', zlib.adler32(data) & 0xFFFFFFFF))
        payload = b''.join(blocks)
    color_type = {3: 2, 4: 6}[c]
    return (b'\x89PNG\r\n\x1a\n' + _crc_chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, color_type, 0, 0, 0))
            + _crc_chunk(b'IDAT', payload) + _crc_chunk(b'IEND', b''))
